/// The letterhead PDF for a management report (decision 01-export-layout).
///
/// One builder for every report, so the paper cannot drift report by report:
/// store identity where it is configured, the report title, period, filters,
/// who generated it and when, the KPI totals first, then the detail table with
/// its column headings repeated on every continuation page and "Page X of Y" at
/// the foot.
///
/// Money arrives already formatted by the viewer (`formatPesoForPrint`), because
/// the bundled OpenSans has no peso glyph and every other printed document in
/// the app spells the currency `PHP`.

/// One KPI tile on paper: the same three fields the on-screen tile shows.
typedef ReportPdfKpi = ({String label, String value, String? caption});

/// What a report with no matching rows prints. An empty export must never look
/// like a failed one, so it says this instead of leaving a blank page.
const String noMatchingRecords = 'No matching records';

/// The page the table is laid out on: A4 portrait, and landscape when the table
/// is too wide to read standing up.
PdfPageFormat reportPdfPageFormat({required bool landscape}) =>
    landscape ? PdfPageFormat.a4.landscape : PdfPageFormat.a4;

/// Philippine Standard Time is UTC+8 all year (no daylight saving), so the shift
/// is a constant with no timezone database behind it.
///
/// Returns a local-shaped `DateTime` holding the Manila wall clock, so the app's
/// one date formatter prints it without shifting it a second time.
DateTime philippineTime(DateTime value) {
  final shifted = value.toUtc().add(const Duration(hours: 8));
  return DateTime(
    shifted.year,
    shifted.month,
    shifted.day,
    shifted.hour,
    shifted.minute,
  );
}

/// What the paper says, before any layout.
///
/// Split out of [renderReportPdf] so a test can read the content directly, the
/// same way `ReceiptContent` serves the receipt.
class ReportPdfContent {
  ReportPdfContent({
    required this.title,
    required this.period,
    this.filters = const [],
    this.generatedBy = '',
    DateTime? generatedAt,
    this.storeName = '',
    this.storeAddress = '',
    this.storeTin = '',
    this.kpis = const [],
    this.columns = const [],
    this.rows = const [],
    this.emptyMessage = noMatchingRecords,
  }) : generatedAt = philippineTime(generatedAt ?? appClock.now());

  final String title;

  /// `Oct 1, 2026 to Oct 30, 2026`, or `As of Oct 30, 2026` for current stock.
  final String period;

  /// The filters actually applied, as the viewer labels them.
  final List<String> filters;

  /// Empty when nobody is signed in: the line then only carries the time.
  final String generatedBy;

  /// Manila wall clock, already shifted by [philippineTime].
  final DateTime generatedAt;

  /// Store identity, empty when the system has it configured nowhere. An
  /// unconfigured fact is omitted, never invented.
  final String storeName;
  final String storeAddress;
  final String storeTin;

  final List<ReportPdfKpi> kpis;
  final List<String> columns;
  final List<List<String>> rows;

  /// Printed in place of the table when [isEmpty].
  final String emptyMessage;

  bool get isEmpty => rows.isEmpty;

  /// The store block: name, then address and TIN only when they are on file.
  List<String> get letterheadLines => [
    if (storeName.trim().isNotEmpty) storeName.trim(),
    if (storeAddress.trim().isNotEmpty) storeAddress.trim(),
    if (storeTin.trim().isNotEmpty) 'TIN: ${storeTin.trim()}',
  ];

  /// One line listing the applied filters, or nothing when none were applied.
  List<String> get filterLines {
    final applied = [
      for (final filter in filters)
        if (filter.trim().isNotEmpty) filter.trim(),
    ];
    return applied.isEmpty ? const [] : ['Filters: ${applied.join(' · ')}'];
  }

  /// `Generated by Ana Cruz · Nov 10, 2026, 3:04 PM PHT`.
  String get generatedLine => [
    if (generatedBy.trim().isNotEmpty) 'Generated by ${generatedBy.trim()}',
    '${formatDateTime(generatedAt)} PHT',
  ].join(' · ');
}

/// The report as PDF bytes, ready to print or share.
Future<Uint8List> renderReportPdf({
  required String title,
  required String period,
  List<String> filters = const [],
  String generatedBy = '',
  DateTime? generatedAt,
  String storeName = '',
  String storeAddress = '',
  String storeTin = '',
  List<ReportPdfKpi> kpis = const [],
  List<String> columns = const [],
  List<List<String>> rows = const [],
  bool landscape = false,

  /// Printed in place of the table when there are no rows. A document that can
  /// legitimately be empty (a quotation with no items) says so in its own
  /// words instead of borrowing the reports' "no matching records".
  String emptyMessage = noMatchingRecords,
}) async {
  String printable(String value) => value.replaceAll('\u20b1', 'PHP ');
  final content = ReportPdfContent(
    title: title,
    period: period,
    filters: filters,
    generatedBy: generatedBy,
    generatedAt: generatedAt,
    storeName: storeName,
    storeAddress: storeAddress,
    storeTin: storeTin,
    kpis: [
      for (final kpi in kpis)
        (
          label: printable(kpi.label),
          value: printable(kpi.value),
          caption: kpi.caption == null ? null : printable(kpi.caption!),
        ),
    ],
    columns: columns.map(printable).toList(),
    rows: [for (final row in rows) row.map(printable).toList()],
    emptyMessage: emptyMessage,
  );
  final document = pw.Document(
    theme: pw.ThemeData.withFont(
      base: pw.Font.ttf(await rootBundle.load(labelFontAsset)),
      bold: pw.Font.ttf(await rootBundle.load(labelBoldFontAsset)),
    ),
  );
  document.addPage(
    pw.MultiPage(
      pageFormat: reportPdfPageFormat(landscape: landscape),
      maxPages: rows.length + 20,
      margin: const pw.EdgeInsets.fromLTRB(32, 28, 32, 34),
      // Page 1 carries the letterhead and the title, so only a continuation
      // page repeats the report identity and the column headings.
      header: (context) => context.pageNumber == 1
          ? pw.SizedBox()
          : _continuationHeader(content),
      footer: _pageFooter,
      build: (context) => [..._identity(content), _table(content)],
    ),
  );
  return document.save();
}

/// The letterhead, the report title with its period and filters, the generation
/// stamp, then the KPI totals — in that reading order, before any detail row.
List<pw.Widget> _identity(ReportPdfContent content) {
  const small = pw.TextStyle(fontSize: 9, color: PdfColors.grey700);
  return [
    if (content.letterheadLines.isNotEmpty) ...[
      pw.Text(
        content.letterheadLines.first,
        style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
      ),
      for (final line in content.letterheadLines.skip(1))
        pw.Text(line, style: small),
      pw.Divider(
        thickness: 1.5,
        color: const PdfColor.fromInt(0xFFAC934F),
        height: 10,
      ),
    ],
    pw.Text(
      content.title,
      style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold),
    ),
    pw.SizedBox(height: 2),
    pw.Text(
      'Period: ${content.period}',
      style: const pw.TextStyle(fontSize: 10),
    ),
    for (final line in content.filterLines) pw.Text(line, style: small),
    pw.Text(content.generatedLine, style: small),
    if (content.kpis.isNotEmpty) ...[
      pw.SizedBox(height: 10),
      _kpiTiles(content.kpis),
    ],
    pw.SizedBox(height: 12),
  ];
}

/// The KPI totals as the row of tiles the screen shows, so a number is never
/// read without the label and the arithmetic behind it.
pw.Widget _kpiTiles(List<ReportPdfKpi> kpis) => pw.Wrap(
  spacing: 8,
  runSpacing: 8,
  children: [
    for (final kpi in kpis)
      pw.Container(
        width: 118,
        padding: const pw.EdgeInsets.all(6),
        decoration: pw.BoxDecoration(
          color: const PdfColor.fromInt(0xFFF8F6F0),
          border: pw.Border.all(color: PdfColors.grey400, width: 0.5),
          borderRadius: const pw.BorderRadius.all(pw.Radius.circular(3)),
        ),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              kpi.label,
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700),
            ),
            pw.SizedBox(height: 2),
            pw.Text(
              kpi.value,
              style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold),
            ),
            if ((kpi.caption ?? '').trim().isNotEmpty) ...[
              pw.SizedBox(height: 2),
              pw.Text(
                kpi.caption!.trim(),
                style: const pw.TextStyle(
                  fontSize: 7,
                  color: PdfColors.grey700,
                ),
              ),
            ],
          ],
        ),
      ),
  ],
);

/// The detail table, or the empty-result sentence in its place.
pw.Widget _table(ReportPdfContent content) {
  if (content.columns.isEmpty) return pw.SizedBox();
  if (content.rows.isEmpty) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey400, width: 0.5),
      ),
      child: pw.Text(
        content.emptyMessage,
        style: const pw.TextStyle(fontSize: 10),
      ),
    );
  }
  return pw.Table(
    border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.5),
    children: [
      _headingRow(content.columns),
      for (final row in content.rows) _bodyRow(row, content.columns.length),
    ],
  );
}

/// What a continuation page opens with, so a row is never read without knowing
/// which report and which columns it belongs to.
pw.Widget _continuationHeader(ReportPdfContent content) => pw.Container(
  padding: const pw.EdgeInsets.only(bottom: 6),
  child: pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.stretch,
    children: [
      pw.Text(
        '${content.title} · ${content.period}',
        style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700),
      ),
      pw.SizedBox(height: 4),
      if (content.rows.isNotEmpty && content.columns.isNotEmpty)
        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.5),
          children: [_headingRow(content.columns)],
        ),
    ],
  ),
);

pw.Widget _pageFooter(pw.Context context) => pw.Container(
  alignment: pw.Alignment.centerRight,
  margin: const pw.EdgeInsets.only(top: 8),
  child: pw.Text(
    'Page ${context.pageNumber} of ${context.pagesCount}',
    style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey700),
  ),
);

pw.TableRow _headingRow(List<String> columns) => pw.TableRow(
  decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFFE1C684)),
  children: [for (final column in columns) _cell(column, bold: true)],
);

pw.TableRow _bodyRow(List<String> row, int columnCount) => pw.TableRow(
  children: [
    for (var index = 0; index < columnCount; index++)
      _cell(index < row.length ? row[index] : ''),
  ],
);

pw.Widget _cell(String text, {bool bold = false}) => pw.Padding(
  padding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
  child: pw.Text(
    text,
    style: pw.TextStyle(
      fontSize: 9,
      fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
    ),
  ),
);
