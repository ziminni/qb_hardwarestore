  /// "Allow fractional quantity?": fractions belong to the UNIT (PC is always
  /// whole, KG is not), so the switch flips to a same-kind unit with the other
  /// rule when the shop has one, and is locked, saying why, when it has none.
  Widget _fractionSwitch(UnitOfMeasure unit) {
    UnitOfMeasure? other;
    for (final candidate in TrackingKind.of(unit).unitsIn(_units)) {
      if (candidate.isWhole != unit.isWhole) {
        other = candidate;
        break;
      }
    }
    final String subtitle;
    if (other == null) {
      subtitle = unit.isWhole
          ? 'Keep this off for indivisible items such as hammers. '
                '${unit.code} is always sold in whole numbers.'
                '${_sellLooseShown ? ' Selling by the half ${unit.code.toLowerCase()}, '
                          'the kilo or the metre? Use Sell loose below.' : ''}'
          : '${unit.code} can be sold in parts, such as 0.5 ${unit.code}.';
    } else {
      subtitle = unit.isWhole
          ? 'Keep this off for indivisible items such as hammers.'
          : 'On: ${unit.code} can be sold in parts. Off switches to '
                '${other.code}, counted in whole numbers.';
    }
    final changeTo = other;
    return SwitchListTile(
      key: const ValueKey('fraction-switch'),
      contentPadding: EdgeInsets.zero,
      title: const Text('Allow fractional quantity?'),
      subtitle: Text(subtitle),
      value: !unit.isWhole,
      onChanged: changeTo == null
          ? null
          : (_) => setState(() => _baseUomId = changeTo.id),
    );
  }

