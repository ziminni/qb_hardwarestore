  /// (a bag, a roll), and not while the base is being swapped for a smaller
  /// pack unit.
  bool get _sellLooseShown {
    final unit = _shownBaseUnit;
    return !_editing &&
        unit != null &&
        unit.isWhole &&
        !(_alsoSoldAsPack && _packIsSmaller);
