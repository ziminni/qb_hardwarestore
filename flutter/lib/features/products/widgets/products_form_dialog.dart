/// What the product form produced: a creation draft, or an edit draft.
///
/// One dialog, two payloads, because the two writes are genuinely different: a
/// create is a chain of POSTs that cannot exist without a category, a brand and a
/// base unit, while an edit is a set of PATCHes over rows that already have ids.
class ProductFormResult {
  const ProductFormResult.create(NewProductDraft this.draft) : edit = null;
  const ProductFormResult.edit(ProductEditDraft this.edit) : draft = null;

  final NewProductDraft? draft;
  final ProductEditDraft? edit;
}

/// The Add / Edit product dialog: the teammate's `ui/frontend-progress` form
/// (owner 2026-11-18), wired to the real catalogue.
///
///  1. **Basic Information**: name, first variant + SKU, factory barcode (blank =
///     auto-generated by the server), category, brand, description, image.
///  2. **Inventory Tracking** (add only): By Quantity / Weight / Length / Volume
///     picks a real base unit; Packaged / Standard lengths adds ONE real selling
///     unit ("Bag = 40 kg"); the fraction switch follows the unit's own rule.
///  3. **Pricing & Initial Stock** (add only): cost, selling price, opening stock
///     (posted to `/variants/{id}/opening-stock/` as a bill-free delivery), reorder
///     level and **Stored at**, with a live Stock Preview.
///
/// Editing shows step 1 plus price, reorder level and Stored at: the base unit
/// is frozen once the product exists, and stock never changes from this form.
class ProductsFormDialog extends StatefulWidget {
  const ProductsFormDialog({
    super.key,
    required this.categories,
    required this.brands,
    required this.units,
    required this.products,
    this.product,
    this.locationHint = '',
    this.storageLocations = const [],
    this.storageLocationError,
    this.imageFileService = const ImageFileService(),
  });

  final List<Category> categories;
  final List<Brand> brands;
  final List<UnitOfMeasure> units;
  final List<Product> products;
  final Product? product;

  /// Where this device says the stock sits. Blank on a product nobody recorded.
  final String locationHint;

  /// The shop's pick-up points as the SERVER answered (Phase 5 B4). Active rows
  /// are offered; the product's own (possibly inactive) one stays visible.
  final List<StorageLocation> storageLocations;

  /// Why the list is not trustworthy, or null.
  ///
  /// A failed read must not become a blank picker that quietly submits the
  /// server's default: the form refuses to create a product until the clerk has
  /// seen a real list (see [_submit]).
  final String? storageLocationError;

  /// The photo picker. Injectable so a test can hand over bytes instead of
  /// opening the OS file dialog.
  final ImageFileService imageFileService;

  @override
  State<ProductsFormDialog> createState() => _ProductsFormDialogState();
}

/// How a measured product's stock is held (teammate form, owner 2026-11-18).
///
/// `packaged` / `standardLengths` add ONE real selling unit ("Bag = 40 kg"),
/// priced at the base price times its size; `direct` / `continuous` sell the
/// base unit only.
enum _StockForm {
  direct('Bulk / Measured'),
  packaged('Packaged'),
  continuous('Continuous / Measured Length'),
  standardLengths('Individual Standard Lengths');

  const _StockForm(this.label);
  final String label;

  bool get hasPackage => this == packaged || this == standardLengths;
}

class _ProductsFormDialogState extends State<ProductsFormDialog> {
  final _formKey = GlobalKey<FormState>();
  late final TextEditingController _nameController;
  late final TextEditingController _descriptionController;
  late final TextEditingController _variantController;
  late final TextEditingController _skuController;
  late final TextEditingController _barcodeController;
  late final TextEditingController _reorderController;
  late final TextEditingController _sellingController;
  late final TextEditingController _creditValueController;

  /// The utang markup kind for the base selling unit (owner ruling): NONE,
  /// AMOUNT or PERCENT. Prefilled from the existing unit when editing, so the
  /// clerk sees what is stored instead of a blank form that would erase it.
  String _creditKind = 'NONE';
  late final TextEditingController _costController;
  late final TextEditingController _initialController;
  late final TextEditingController _packageSizeController;
  int? _categoryId;
  int? _brandId;
  int? _baseUomId;
  int? _packageUomId;
  _StockForm _stockForm = _StockForm.direct;

  /// The product's STORED photo URL (the server's, or a legacy one). Never a path
  /// this device invented.
  late String _imageUrl;

  /// The photo the clerk picked in THIS dialog, held as bytes until save.
  ProductImageUpload? _imageUpload;

  /// Why the last pick failed, or null.
  String? _imageError;

  /// The SERVER pick-up point this product is stored at (Phase 5 B4).
  int? _storedAtId;

  /// True once the clerk picked a location themselves (item 12).
  bool _storedAtTouched = false;

  /// Whether a LINE of this product may be discounted (owner ruling: cement is
  /// never discounted). Prefilled from the product so an edit shows what is stored,
  /// and remembered as TOUCHED so a save that only fixes a name leaves it alone.
  late bool _allowDiscount;
  bool _allowDiscountTouched = false;

  bool get _editing => widget.product != null;

  ProductVariant? get _variant => widget.product?.variants.firstOrNull;

  UnitOfMeasure? _unitWithId(int? id) {
    for (final unit in widget.units) {
      if (unit.id == id) return unit;
    }
    return null;
  }

  /// The base unit the form is showing: the picked one when adding, the
  /// variant's frozen one when editing (null when the list has no such row).
  UnitOfMeasure? get _shownBaseUnit {
    if (!_editing) return _unitWithId(_baseUomId);
    final code = _variant?.baseUomCode ?? '';
    for (final unit in widget.units) {
      if (unit.code == code) return unit;
    }
    return null;
  }

  /// The base unit's code, which every price and quantity label prints.
  String get _baseCode {
    if (_editing) return _variant?.baseUomCode ?? '';
    return _unitWithId(_baseUomId)?.code ?? '';
  }

  TrackingKind get _kind {
    final unit = _shownBaseUnit;
    return unit == null ? TrackingKind.quantity : TrackingKind.of(unit);
  }

  List<_StockForm> get _stockOptions => switch (_kind) {
    TrackingKind.quantity => const [_StockForm.direct],
    TrackingKind.length => const [
      _StockForm.continuous,
      _StockForm.standardLengths,
    ],
    _ => const [_StockForm.direct, _StockForm.packaged],
  };

  /// Whole, counted units a package can be: Bag, Box, Pack, Roll, Piece...
  List<UnitOfMeasure> get _packageUnits => [
    for (final unit in widget.units)
      if (unit.isWhole &&
          TrackingKind.of(unit) == TrackingKind.quantity &&
          unit.id != _baseUomId)
        unit,
  ];

  @override
  void initState() {
    super.initState();
    final product = widget.product;
    final variant = _variant;
    _nameController = TextEditingController(text: product?.baseName ?? '');
    _descriptionController = TextEditingController(
      text: product?.description ?? '',
    );
    _variantController = TextEditingController(
      text: variant?.variantName ?? 'Standard',
    );
    _skuController = TextEditingController(text: variant?.sku ?? '');
    // The BASE unit's code, not the variant's first non-blank one: this field
    // writes the factor-1 selling unit (Phase 6 decisions 11 F3 and 18).
    _barcodeController = TextEditingController(text: _baseUnitCode(variant));
    _reorderController = TextEditingController(
      text: variant == null ? '10' : formatQuantity(variant.minStockThreshold),
    );
    _sellingController = TextEditingController(
      text: formatQuantity(_baseSellingUnit(variant)?.defaultSellingPrice ?? 0),
    );
    final baseUnit = _baseSellingUnit(variant);
    _creditKind = baseUnit?.creditMarkupKind ?? 'NONE';
    _creditValueController = TextEditingController(
      text: (baseUnit == null || baseUnit.creditMarkupValue == 0)
          ? ''
          : formatQuantity(baseUnit.creditMarkupValue),
    );
    _costController = TextEditingController(text: '0');
    _initialController = TextEditingController(text: '0');
    _packageSizeController = TextEditingController(text: '40');
    _categoryId = product?.categoryId ?? widget.categories.firstOrNull?.id;
    _brandId = product?.brandId ?? widget.brands.firstOrNull?.id;
    _baseUomId = variant?.baseUomId ?? widget.units.firstOrNull?.id;
    _packageUomId = _packageUnits.firstOrNull?.id;
    _imageUrl = product?.imageUrl ?? '';
    _storedAtId = product?.storedAtId ?? _defaultStoredAtId();
    _allowDiscount = product?.allowDiscount ?? true;
  }

  /// What a NEW product is stored at: the row NAMED **Store**, the server's own
  /// default. Null when the list holds no Store, and the field then makes the
  /// clerk choose instead of guessing.
  int? _defaultStoredAtId() {
    for (final location in widget.storageLocations) {
      if (location.isActive && location.name.toLowerCase() == 'store') {
        return location.id;
      }
    }
    return null;
  }

  /// Every ACTIVE location, plus this product's own place when it is inactive or
  /// no longer listed, so an edit never silently re-points it.
  List<StorageLocation> get _storedAtOptions {
    final options = [
      for (final location in widget.storageLocations)
        if (location.isActive) location,
    ];
    final currentId = widget.product?.storedAtId;
    if (currentId != null && !options.any((l) => l.id == currentId)) {
      options.add(
        StorageLocation(
          id: currentId,
          name: widget.product!.storedAtName,
          isActive: false,
        ),
      );
    }
    return options;
  }

  String _storedAtLabel(StorageLocation location) {
    final name = location.name.trim();
    final label = name.isEmpty ? 'Unnamed location' : name;
    return location.isActive ? label : '$label (inactive)';
  }

  String get _storedAtName {
    for (final location in _storedAtOptions) {
      if (location.id == _storedAtId) return location.name;
    }
    return '';
  }

  bool get _storedAtChanged =>
      _storedAtTouched && _storedAtId != widget.product?.storedAtId;

  @override
  void dispose() {
    for (final controller in [
      _nameController,
      _descriptionController,
      _variantController,
      _skuController,
      _barcodeController,
      _reorderController,
      _sellingController,
      _costController,
      _initialController,
      _packageSizeController,
    ]) {
      controller.dispose();
    }
    super.dispose();
  }

  /// Picks a photo and keeps its BYTES (the server refuses a local path).
  Future<void> _selectImage() async {
    try {
      final picked = await widget.imageFileService.selectImage();
      if (!mounted || picked == null) return;
      setState(() {
        _imageUpload = picked;
        _imageError = null;
      });
    } on ImageFileException catch (error) {
      if (!mounted) return;
      setState(() => _imageError = error.message);
    }
  }

  /// The selling unit that IS the base unit: `base_uom` at factor 1. List order
  /// is not identity (a bag may be listed first).
  VariantUom? _baseSellingUnit(ProductVariant? variant) {
    if (variant == null) return null;
    for (final unit in variant.sellingUoms) {
      if (unit.uomId == variant.baseUomId && unit.conversionFactor == 1) {
        return unit;
      }
    }
    return null;
  }

  String _baseUnitCode(ProductVariant? variant) {
    final base = _baseSellingUnit(variant);
    if (base != null) return base.barcodeQr;
    return variant?.barcode ?? '';
  }

  /// True once the clerk touched the markup controls, so an edit sends them
  /// only then (null means "leave the stored markup alone").
  bool _creditMarkupChanged = false;

  /// The markup value in pesos or percent; `NONE` always sends 0, which is what
  /// the server normalises a switched-off markup to anyway.
  double get _creditValue =>
      _creditKind == 'NONE' ? 0 : _num(_creditValueController);

  double _num(TextEditingController controller) =>
      double.tryParse(controller.text.trim().replaceAll(',', '')) ?? 0;

  bool get _packaged => !_editing && _stockForm.hasPackage;

  /// Opening stock in BASE units: packages x size when packaged.
  double get _openingBaseQty => _packaged
      ? _num(_initialController) * _num(_packageSizeController)
      : _num(_initialController);

  void _pickKind(TrackingKind kind) {
    final options = kind.unitsIn(widget.units);
    if (options.isEmpty) return;
    setState(() {
      _baseUomId = options.first.id;
      _stockForm = _stockOptions.first;
      if (_packageUomId == _baseUomId) {
        _packageUomId = _packageUnits.firstOrNull?.id;
      }
    });
  }

  static String? _validatePrice(String? raw) {
    final value = double.tryParse(raw?.trim().replaceAll(',', '') ?? '');
    if (value == null) return 'Enter a price.';
    if (value < 0) return 'The price cannot be negative.';
    return null;
  }

  String? _validateBasePrice(String? raw) {
    if (_editing && _baseSellingUnit(_variant) == null) {
      return 'This product has no base selling unit to price.';
    }
    return _validatePrice(raw);
  }

  static String? _nonNegative(String? value) {
    final parsed = double.tryParse(value?.trim().replaceAll(',', '') ?? '');
    if (parsed == null) return 'Enter a number.';
    if (parsed < 0) return 'Cannot be negative.';
    return null;
  }

  String? _validateInitial(String? raw) {
    final error = _nonNegative(raw);
    if (error != null) return error;
    final value = _num(_initialController);
    if (_packaged && value != value.roundToDouble()) {
      return 'Count whole packages.';
    }
    final base = _openingBaseQty;
    final unit = _shownBaseUnit;
    if (unit != null && unit.isWhole && base != base.roundToDouble()) {
      return '${unit.code} is counted in whole numbers.';
    }
    if ((base * 100).roundToDouble() != base * 100) {
      return 'Use at most two decimal places.';
    }
    return null;
  }

  void _submit() {
    if (!_formKey.currentState!.validate()) return;
    final price = _num(_sellingController);
    final threshold = _num(_reorderController);
    final barcode = _barcodeController.text.trim();

    final existing = widget.product;
    if (existing == null) {
      final size = _num(_packageSizeController);
      final package = _unitWithId(_packageUomId);
      Navigator.of(context).pop(
        ProductFormResult.create(
          NewProductDraft(
            categoryId: _categoryId!,
            brandId: _brandId!,
            baseName: _nameController.text.trim(),
            description: _descriptionController.text.trim(),
            imageUrl: _imageUrl,
            image: _imageUpload,
            variantName: _variantController.text.trim(),
            sku: _skuController.text.trim(),
            baseUomId: _baseUomId!,
            minStockThreshold: threshold,
            maxStockLevel: 0,
            sellingPrice: price,
            creditMarkupKind: _creditKind,
            creditMarkupValue: _creditValue,
            barcodeQr: barcode,
            locationHint: widget.locationHint,
            storedAtId: _storedAtId,
            allowDiscount: _allowDiscount,
            extraSellingUnits: [
              if (_packaged && package != null)
                NewSellingUnit(
                  uomId: package.id,
                  uomCode: package.code,
                  conversionFactor: size,
                  sellingPrice: double.parse((price * size).toStringAsFixed(2)),
                  barcodeQr: '',
                ),
            ],
            openingQty: _openingBaseQty,
            openingUnitCost: _num(_costController),
          ),
        ),
      );
      return;
    }

    final variant = _variant;
    Navigator.of(context).pop(
      ProductFormResult.edit(
        ProductEditDraft(
          productId: existing.id,
          variantId: variant?.id ?? 0,
          sellingUnitId: _baseSellingUnit(variant)?.id ?? 0,
          baseName: _nameController.text.trim(),
          description: _descriptionController.text.trim(),
          categoryId: _categoryId,
          brandId: _brandId,
          variantName: _variantController.text.trim(),
          sku: _skuController.text.trim(),
          minStockThreshold: threshold,
          sellingPrice: price,
          // Only sent when the clerk actually changed the markup, so an edit
          // that touches a price cannot silently clear a stored markup.
          creditMarkupKind: _creditMarkupChanged ? _creditKind : null,
          creditMarkupValue: _creditMarkupChanged ? _creditValue : null,
          barcodeQr: barcode,
          locationHint: widget.locationHint,
          storedAtId: _storedAtChanged ? _storedAtId : null,
          // Only when the clerk touched it: an untouched switch must not PATCH the
          // stored flag back on cement.
          allowDiscount: _allowDiscountTouched ? _allowDiscount : null,
          image: _imageUpload,
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return AppDialog(
      icon: _editing ? Icons.edit_note_rounded : Icons.add_box_outlined,
      title: _editing ? 'Edit product' : 'Add product',
      subtitle: _editing
          ? widget.product!.baseName
          : 'Create a catalog item with its tracking and pricing',
      width: 600,
      content: Form(
        key: _formKey,
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            const FormStepHeader(step: 1, title: 'Basic Information'),
            const SizedBox(height: AppSpacing.md),
            ..._basicInformation(context),
            const SizedBox(height: AppSpacing.lg),
            if (_editing) ...[
              const FormStepHeader(step: 2, title: 'Pricing & Stock Levels'),
              const SizedBox(height: AppSpacing.md),
              ..._editPricing(),
            ] else ...[
              const FormStepHeader(step: 2, title: 'Inventory Tracking'),
              const SizedBox(height: AppSpacing.xs),
              ..._inventoryTracking(context),
              const SizedBox(height: AppSpacing.lg),
              const FormStepHeader(step: 3, title: 'Pricing & Initial Stock'),
              const SizedBox(height: AppSpacing.md),
              ..._pricingAndInitialStock(),
              const SizedBox(height: AppSpacing.lg),
              _preview(context),
            ],
          ],
        ),
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.of(context).pop(),
          child: const Text('Cancel'),
        ),
        FilledButton(
          key: const ValueKey('product-form-submit'),
          onPressed: _submit,
          child: Text(_editing ? 'Save changes' : 'Add product'),
        ),
      ],
    );
  }

  List<Widget> _basicInformation(BuildContext context) => [
    TextFormField(
      controller: _nameController,
      autofocus: true,
      decoration: const InputDecoration(labelText: 'Product name'),
      validator: (value) => value == null || value.trim().isEmpty
          ? 'Enter a product name.'
          : null,
    ),
    const SizedBox(height: AppSpacing.xl),
    Text(
      _editing ? 'Variant' : 'First variant',
      style: Theme.of(context).textTheme.titleSmall,
    ),
    const SizedBox(height: AppSpacing.md),
    TextFormField(
      controller: _variantController,
      decoration: const InputDecoration(labelText: 'Variant name'),
      validator: (value) => value == null || value.trim().isEmpty
          ? 'Enter a variant name.'
          : null,
    ),
    const SizedBox(height: AppSpacing.md),
    TextFormField(
      key: const ValueKey('sku-field'),
      controller: _skuController,
      decoration: const InputDecoration(labelText: 'SKU'),
      validator: (value) => !_editing && (value == null || value.trim().isEmpty)
          ? 'Enter an SKU.'
          : null,
    ),
    const SizedBox(height: AppSpacing.md),
    TextFormField(
      controller: _barcodeController,
      decoration: const InputDecoration(
        labelText: 'Factory barcode (leave blank to auto-generate)',
        hintText: 'Scan or type the code printed on the package',
        prefixIcon: Icon(Icons.barcode_reader),
        helperText: 'One barcode identifies this main product package.',
      ),
      validator: (value) {
        final barcode = value?.trim() ?? '';
        if (barcode.isEmpty) return null;
        final duplicate = widget.products.any(
          (product) =>
              product.id != widget.product?.id &&
              product.variants.any(
                (variant) =>
                    variant.barcode.toLowerCase() == barcode.toLowerCase(),
              ),
        );
        return duplicate
            ? 'This barcode is already assigned to another product.'
            : null;
      },
    ),
    const SizedBox(height: AppSpacing.lg),
    DropdownButtonFormField<int>(
      key: const ValueKey('category-picker'),
      isExpanded: true,
      initialValue: _categoryId,
      decoration: const InputDecoration(labelText: 'Category'),
      items: widget.categories
          .where(
            (category) =>
                category.isActive || category.id == widget.product?.categoryId,
          )
          .map(
            (category) => DropdownMenuItem(
              value: category.id,
              child: Text(category.name, overflow: TextOverflow.ellipsis),
            ),
          )
          .toList(),
      validator: (value) => value == null ? 'Choose a category.' : null,
      onChanged: (value) {
        if (value != null) setState(() => _categoryId = value);
      },
    ),
    const SizedBox(height: AppSpacing.lg),
    DropdownButtonFormField<int>(
      key: const ValueKey('brand-picker'),
      isExpanded: true,
      initialValue: _brandId,
      decoration: const InputDecoration(labelText: 'Brand'),
      items: widget.brands
          .map(
            (brand) => DropdownMenuItem(
              value: brand.id,
              child: Text(brand.name, overflow: TextOverflow.ellipsis),
            ),
          )
          .toList(),
      validator: (value) => value == null ? 'Choose a brand.' : null,
      onChanged: (value) {
        if (value != null) setState(() => _brandId = value);
      },
    ),
    const SizedBox(height: AppSpacing.lg),
    TextFormField(
      controller: _descriptionController,
      maxLines: 3,
      decoration: const InputDecoration(labelText: 'Description'),
    ),
    const SizedBox(height: AppSpacing.lg),
    Text('Product image', style: Theme.of(context).textTheme.labelLarge),
    const SizedBox(height: AppSpacing.sm),
    _ImagePicker(
      imageUrl: _imageUrl,
      imageBytes: _imageUpload?.bytes,
      filename: _imageUpload?.filename,
      error: _imageError,
      onPick: _selectImage,
      onRemove: _editing
          ? null
          : () => setState(() {
              _imageUrl = '';
              _imageUpload = null;
            }),
    ),
  ];

  List<Widget> _inventoryTracking(BuildContext context) {
    final kind = _kind;
    final unit = _shownBaseUnit;
    return [
      const Text('How is this product tracked?'),
      const SizedBox(height: AppSpacing.md),
      Wrap(
        spacing: AppSpacing.sm,
        runSpacing: AppSpacing.sm,
        children: [
          for (final option in TrackingKind.values)
            ChoiceChip(
              key: ValueKey('tracking-${option.name}'),
              label: Text(option.label),
              selected: option == kind,
              onSelected: option.unitsIn(widget.units).isEmpty
                  ? null
                  : (_) => _pickKind(option),
            ),
        ],
      ),
      const SizedBox(height: AppSpacing.sm),
      Text(kind.caption, style: Theme.of(context).textTheme.bodySmall),
      const SizedBox(height: AppSpacing.lg),
      DropdownButtonFormField<int>(
        key: const ValueKey('base-unit-picker'),
        isExpanded: true,
        initialValue: _baseUomId,
        decoration: const InputDecoration(
          labelText: 'Base measurement / unit',
          helperText:
              'Set once: a variant keeps this unit for its whole history.',
        ),
        items: [
          for (final option
              in kind.unitsIn(widget.units).isEmpty
                  ? widget.units
                  : kind.unitsIn(widget.units))
            DropdownMenuItem(value: option.id, child: Text(option.label)),
        ],
        validator: (value) => value == null ? 'Choose a base unit.' : null,
        onChanged: (value) {
          if (value != null) setState(() => _baseUomId = value);
        },
      ),
      if (kind != TrackingKind.quantity) ...[
        const SizedBox(height: AppSpacing.md),
        SegmentedButton<_StockForm>(
          key: const ValueKey('stock-form'),
          segments: [
            for (final form in _stockOptions)
              ButtonSegment(value: form, label: Text(form.label)),
          ],
          selected: {
            _stockOptions.contains(_stockForm)
                ? _stockForm
                : _stockOptions.first,
          },
          onSelectionChanged: (values) =>
              setState(() => _stockForm = values.first),
        ),
      ],
      if (_stockForm.hasPackage && kind != TrackingKind.quantity) ...[
        const SizedBox(height: AppSpacing.md),
        Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Expanded(
              child: DropdownButtonFormField<int>(
