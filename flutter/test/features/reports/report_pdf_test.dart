// Reports suite P3 (decision 01-export-layout): the letterhead PDF every
// management report exports.
//
// The paper is checked without a printer: the identity it may print (store
// name, address, TIN) and the identity it must NOT invent, the period, the
// filters, the generation stamp in Philippine time, the KPIs before the rows,
// the empty-result sentence, and the fact that a missing cost keeps the
// viewer's words instead of becoming a zero.

import 'package:client/features/reports/report_pdf.dart';
import 'package:flutter_test/flutter_test.dart';

ReportPdfContent _content({
  List<String> filters = const [],
  String generatedBy = 'Ana Cruz',
  String storeName = 'QB Hardware & Construction Supplies',
  String storeAddress = '',
  String storeTin = '',
  List<String> columns = const ['Day', 'Transactions', 'Invoice total'],
  List<List<String>> rows = const [
    ['Oct 29, 2026', '2', 'PHP 1,000.00'],
  ],
}) => ReportPdfContent(
  title: 'Sales summary',
  period: 'Oct 1, 2026 to Oct 30, 2026',
  filters: filters,
  generatedBy: generatedBy,
  generatedAt: DateTime.utc(2026, 11, 10, 7, 4),
  storeName: storeName,
  storeAddress: storeAddress,
  storeTin: storeTin,
  kpis: const [
    (label: 'Transactions', value: '3', caption: 'Completed sales'),
    (label: 'Invoice total', value: 'PHP 1,500.00', caption: null),
  ],
  columns: columns,
  rows: rows,
);

void main() {
  group('ReportPdfContent', () {
    test('the letterhead prints the store it was configured with, nothing '
        'invented', () {
      final content = _content();

      expect(content.letterheadLines, ['QB Hardware & Construction Supplies']);

      // No address and no TIN are configured, so neither is printed.
      expect(
        content.letterheadLines.where((line) => line.startsWith('TIN:')),
        isEmpty,
      );
      expect(
        content.letterheadLines.where(
          (line) => line.contains('Address') || line.contains('Cebu'),
        ),
        isEmpty,
      );
    });

    test('an address and TIN on file are printed under the store name', () {
      final content = _content(
        storeAddress: '12 Mabini St, Cebu City',
        storeTin: '123-456-789-000',
      );

      expect(content.letterheadLines, [
        'QB Hardware & Construction Supplies',
        '12 Mabini St, Cebu City',
        'TIN: 123-456-789-000',
      ]);
    });

    test('the title, period and applied filters sit above the tiles', () {
      final content = _content(filters: ['All cashiers']);

      expect(content.title, 'Sales summary');
      expect(content.period, 'Oct 1, 2026 to Oct 30, 2026');
      expect(content.filterLines, ['Filters: All cashiers']);
    });

    test('no filter means no filter line, not an empty one', () {
      expect(_content().filterLines, isEmpty);
    });

    test('the generation stamp names the user and reads Philippine time', () {
      // 07:04 UTC is 3:04 PM in the Philippines (UTC+8).
      final content = _content();

      expect(
        content.generatedLine,
        'Generated by Ana Cruz · Nov 10, 2026, 3:04 PM PHT',
      );
    });

    test('a missing cost keeps the viewer\'s words and is never a zero', () {
      final content = _content(
        rows: const [
          ['Portland cement', 'No cost on file', 'PHP 0.00'],
        ],
      );

      expect(content.rows.single, [
        'Portland cement',
        'No cost on file',
        'PHP 0.00',
      ]);
      expect(content.isEmpty, isFalse);
    });

    test('an empty result says "No matching records" instead of printing '
        'nothing', () {
      final content = _content(rows: const []);

      expect(content.isEmpty, isTrue);
      expect(content.emptyMessage, 'No matching records');
    });
  });

  group('reportPdfPageFormat', () {
    test('A4 portrait for a normal table', () {
      final format = reportPdfPageFormat(landscape: false);

      expect(format.height, greaterThan(format.width));
    });

    test('A4 landscape for a wide table', () {
      final format = reportPdfPageFormat(landscape: true);

      expect(format.width, greaterThan(format.height));
    });
  });

  group('renderReportPdf', () {
    test('renders a real PDF with the letterhead and the detail rows', () async {
      TestWidgetsFlutterBinding.ensureInitialized();

      final bytes = await renderReportPdf(
        title: 'Sales summary',
        period: 'Oct 1, 2026 to Oct 30, 2026',
        filters: const ['All cashiers'],
        generatedBy: 'Ana Cruz',
        generatedAt: DateTime.utc(2026, 11, 10, 7, 4),
        storeName: 'QB Hardware & Construction Supplies',
        kpis: const [
          (label: 'Transactions', value: '3', caption: 'Completed sales'),
        ],
        columns: const ['Day', 'Transactions', 'Invoice total'],
        rows: const [
          ['Oct 29, 2026', '2', 'PHP 1,000.00'],
        ],
      );

      expect(bytes, isNotEmpty);
      expect(String.fromCharCodes(bytes.take(5)), '%PDF-');
      expect(_pdfPageCount(bytes), 1);
    });

    test('a long table continues over pages instead of clipping', () async {
      TestWidgetsFlutterBinding.ensureInitialized();

      final bytes = await renderReportPdf(
        title: 'Sales summary',
        period: 'Oct 1, 2026 to Oct 30, 2026',
        columns: const ['Day', 'Transactions', 'Invoice total'],
        rows: [
          for (var day = 1; day <= 120; day++)
            ['Oct $day, 2026', '$day', 'PHP ${day * 100}.00'],
        ],
      );

      expect(_pdfPageCount(bytes), greaterThan(1));
    });

    test('an empty result still renders one page', () async {
      TestWidgetsFlutterBinding.ensureInitialized();

      final bytes = await renderReportPdf(
        title: 'Sales summary',
        period: 'Oct 1, 2026 to Oct 30, 2026',
        columns: const ['Day', 'Transactions', 'Invoice total'],
        rows: const [],
      );

      expect(_pdfPageCount(bytes), 1);
    });
  });
}

/// How many pages a PDF really carries: the object dictionary marks each one.
int _pdfPageCount(List<int> bytes) {
  final text = String.fromCharCodes(bytes);
  return RegExp(r'/Type\s*/Page[^s]').allMatches(text).length;
}
